def menu():
    print("\n===== MAPA COLABORATIVO DE PROBLEMAS URBANOS =====")
    print("1 - Cadastrar ocorrência")
    print("2 - Listar todas")
    print("3 - Buscar por categoria")
    print("4 - Buscar por bairro/região")
    print("5 - Listar ordenado")
    print("6 - Estatísticas")
    print("7 - Carregar dados de exemplo")
    print("0 - Sair")
    return ler_inteiro("Opção: ", 0, 7)


def main():
    opcao = -1
    while opcao != 0:
        opcao = menu()
        if opcao == 1:
            cadastrar()
        elif opcao == 2:
            listar()
        elif opcao == 3:
            buscar_categoria()
        elif opcao == 4:
            buscar_bairro()
        elif opcao == 5:
            listar_ordenado()
        elif opcao == 6:
            estatisticas()
        elif opcao == 7:
            carregar_exemplos()
    print("Encerrando. Obrigado por colaborar com a sua cidade!")


main()